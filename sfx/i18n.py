from __future__ import annotations

from PySide6.QtCore import QLocale, QSettings

LANGS = {"ru": "Русский", "en": "English"}


def _settings() -> QSettings:
    return QSettings("sfx", "sfx")


def _detect() -> str:
    lang = _settings().value("lang", "")
    if lang in LANGS:
        return lang
    return "ru" if QLocale.system().name().startswith(("ru", "uk", "be")) else "en"


LANG = _detect()


def set_lang(lang: str):
    _settings().setValue("lang", lang)


def tr(s: str) -> str:
    if LANG == "ru":
        return s
    return EN.get(s, s)


